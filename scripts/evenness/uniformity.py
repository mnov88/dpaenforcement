"""Phase 2 – uniformity testing for GDPR enforcement outcomes.

This module builds on the Phase 1 artefacts to assess whether enforcement
outcomes are conditionally independent of jurisdiction once facts are taken
into account.  It provides utilities for:

* cross-fitted nuisance modelling (orthogonalised residuals);
* conditional randomisation tests against country and DPA groupings;
* matched-pair disparity statistics across the twin constructions;
* distributional equality diagnostics (KS/EMD/quantile contrasts);
* hierarchical invariance checks via mixed-effects models; and
* calibration summaries across risk bands.

All heavy lifting happens with pandas/NumPy/Statsmodels/Scikit-learn, keeping
dependencies aligned with the rest of the analysis stack.
"""

